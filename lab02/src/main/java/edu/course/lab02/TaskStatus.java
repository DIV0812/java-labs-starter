package edu.course.lab02;          // пакет, совпадает со структурой папок

/**
 * Перечисление статусов задачи.
 * Начальный статус новой задачи — NEW.
 */
public enum TaskStatus {          // enum — тип с фиксированным набором значений
    NEW,                          // задача только что создана
    IN_PROGRESS,                  // задача в работе
    DONE,                         // задача завершена
    CANCELLED                     // задача отменена
}